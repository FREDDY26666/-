const RARITY_TABLE = [
  { rarity: '일반', weight: 0.55, mp: [1, 2], atk: [4, 8], def: [3, 6] },
  { rarity: '희귀', weight: 0.30, mp: [3, 4], atk: [8, 13], def: [6, 10] },
  { rarity: '전설', weight: 0.15, mp: [5, 6], atk: [13, 20], def: [10, 15] }
];

function pickRarity(seed) {
  // 결정론적 분포: 이름 해시 기반으로 5:3:1.5 비율에 맞춰 순환 배정
  const pattern = ['일반', '일반', '희귀', '일반', '전설', '희귀', '일반', '희귀', '일반', '일반'];
  return pattern[seed % pattern.length];
}

function statFor(rarity, kind, index) {
  const table = RARITY_TABLE.find((r) => r.rarity === rarity);
  const range = kind === 'atk' ? table.atk : kind === 'def' ? table.def : table.mp;
  const span = range[1] - range[0];
  const value = range[0] + (index % (span + 1));
  return value;
}

// ---------------------------------------------------------------------------
// 카드 생성
// ---------------------------------------------------------------------------

let seq = 0;
const cards = [];

function addCard({ subject, type, name, flavor, forcedMp }) {
  seq += 1;
  const rarity = pickRarity(seq);
  const mp = forcedMp != null ? forcedMp : statFor(rarity, 'mp', seq);
  const id = `${subject}_${type}_${String(seq).padStart(3, '0')}`;

  const card = {
    id,
    subject, // 수학/영어/국어/통합사회/통합과학/한국사/공용
    type, // 공격/방어/유틸
    name,
    rarity,
    mp,
    front_text: '', // 게임적 정보(아래에서 타입별로 채움)
    flavor // 카드 하단/뒷면 개념 설명
  };

  if (type === '공격') {
    const dmg = statFor(rarity, 'atk', seq);
    card.damage = dmg;
    card.front_text = `MP ${mp} 소모, 대상에게 데미지 ${dmg}.`;
  } else if (type === '방어') {
    const shield = statFor(rarity, 'def', seq);
    card.shield = shield;
    card.front_text = `MP ${mp} 소모, 받는 데미지 ${shield}만큼 감소(1회).`;
  } else {
    // 유틸 / 체육 / 진로는 효과가 카드마다 달라 간단한 보정 수치로 통일
    const util = Math.max(1, Math.round(statFor(rarity, 'mp', seq) / 1));
    card.utility_value = util;
    card.front_text = `MP ${mp} 소모, 진영 특성에 맞는 특수 효과(보정치 ${util}) 1회 적용.`;
  }

  cards.push(card);
}

for (const [subject, group] of Object.entries(BANKS)) {
  if (subject === '공용') {
    for (const [listName, items] of Object.entries(group)) {
      if (listName === 'color') continue;
      // 공용 카드는 모두 '유틸' 계열로 취급하되 체육/진로 구분은 tag로 남김
      for (const [name, flavor] of items) {
        addCard({ subject: '공용', type: '유틸', name: `${name}`, flavor: `[${listName}] ${flavor}` });
      }
    }
    continue;
  }
  for (const [type, items] of Object.entries(group)) {
    if (type === 'color') continue;
    for (const [name, flavor] of items) {
      addCard({ subject, type, name, flavor });
    }
  }
}

